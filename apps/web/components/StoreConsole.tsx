/**
 * Provenance is stated on every panel, never inferred by the reader.
 *
 * `synthetic_only` is the important one: those records have no live counterpart and never
 * will, because the scope that would produce them is not granted. Saying so on the panel is
 * what keeps a demo surface from being read as operational truth.
 */
function ProvenanceNote({ provenance }: { provenance: StoreProvenance }) {
  if (provenance === "provider_backed") return null;
  const synthetic = provenance === "synthetic_only";
  return (
    <p className={synthetic ? "inline-warning" : "muted small"} role="note">
      {synthetic
        ? "Synthetic · no live equivalent. These records are generated locally for display and are never used to plan, quote or certify work."
        : "Synthetic · generated by the local fake store. Not a real merchant record."}
    </p>
  );
}

function money(amount: string, currency: string) {
  const value = Number(amount);
  return Number.isFinite(value)
    ? new Intl.NumberFormat(undefined, {
        style: "currency",
        currency: currency || "CAD",
      }).format(value)
    : `${amount} ${currency}`;
}

/** A tiny inline bar chart. Deliberately plain: it reports values, it does not decorate. */
function SalesBars({
  daily,
  currency,
}: {
  daily: StoreAnalytics["daily"];
  currency: string;
}) {
  const peak = daily.reduce(
    (max, point) => Math.max(max, Number(point.grossSales)),
    0,
  );
  if (!peak) return null;
  return (
    <ul className="store-bars">
      {daily.map((point) => {
        const value = Number(point.grossSales);
        return (
          <li key={point.day}>
            <span
              className="store-bar"
              style={{ height: `${Math.max(2, (value / peak) * 100)}%` }}
              aria-hidden="true"
            />
            <span className="store-bar-label">
              {point.day.slice(5)} · {money(point.grossSales, currency)} ·{" "}
              {point.orderCount} orders
            </span>
          </li>
        );
      })}
    </ul>
  );
}

function CatalogPanel({ data }: { data: StoreCatalog }) {
  return (
    <>
      <ProvenanceNote provenance={data.provenance} />
      <p className="muted small">
        Showing {data.products.length} of {data.total} products · captured{" "}
        {dateLabel(data.capturedAt, true)}
      </p>
      <ul className="store-list">
        {data.products.map((product) => (
          <li key={product.productGid}>
            <div className="store-row-head">
              <strong>{product.title}</strong>
              <span className="muted small">{product.status}</span>
            </div>
            <p className="muted small">
              {product.vendor ?? "Unknown vendor"} ·{" "}
              {product.productType ?? "Uncategorised"} ·{" "}
              <code>{product.handle}</code>
            </p>
            <table className="store-table">
              <thead>
                <tr>
                  <th scope="col">SKU</th>
                  <th scope="col">Variant</th>
                  <th scope="col">Price</th>
                  <th scope="col">Available</th>
                </tr>
              </thead>
              <tbody>
                {product.variants.map((variant) => {
                  const admin = variantAdminUrl(
                    data.shopDomain,
                    variant.variantGid,
                  );
                  return (
                    <tr key={variant.variantGid}>
                      <td>
                        {admin ? (
                          <a href={admin} target="_blank" rel="noreferrer">
                            <code>{variant.sku ?? "—"}</code>
                          </a>
                        ) : (
                          <code>{variant.sku ?? "—"}</code>
                        )}
                      </td>
                      <td>{variant.title ?? "—"}</td>
                      <td>
                        {variant.price
                          ? money(variant.price, variant.currency ?? "CAD")
                          : "—"}
                      </td>
                      <td>
                        {!variant.tracked
                          ? "Not tracked"
                          : // A null quantity is an unknown, not a zero.
                            (variant.available ?? "Unknown")}
                      </td>
                    </tr>
                  );
                })}
              </tbody>
            </table>
          </li>
        ))}
      </ul>
    </>
  );
}


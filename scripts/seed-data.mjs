function build(role, p) {
  const {
    title,
    type,
    desc,
    tags = [],
    options = null,
    price,
    stock = [40, 400],
    kind = "supply",
    exact = false,
  } = p;
  const r = rng(role + "|" + title);
  const opts = options ?? { Title: ["Default Title"] };
  const variants = cartesian(opts).map((combo, i) => {
    const raw = typeof price === "function" ? price(combo, i) : price;
    const jitter = typeof price === "function" || exact ? 1 : 0.96 + r() * 0.08;
    return {
      optionValues: combo,
      price: money(raw * jitter),
      sku: `${role.slice(0, 3)}-${slug(title).slice(0, 24)}-${i + 1}`.toUpperCase(),
      tracked: stock !== null,
      quantity: stock
        ? Math.round(stock[0] + r() * (stock[1] - stock[0]))
        : null,
    };
  });
  return {
    handle: `${role}-${slug(title)}`.slice(0, 200),
    title,
    type,
    vendor: VENDORS[role] ?? role,
    descriptionHtml: `<p>Synthetic demonstration data; not a verified merchant quote.</p><p>${desc}</p>`,
    tags: [
      "MOLECULE_DEMO",
      `merchant:${MERCHANT_IDS[role] ?? role}`,
      `kind:${kind}`,
      ...tags,
    ],
    options: opts,
    variants,
  };
}

const TIERS = ["12-24", "25-49", "50-99", "100-249", "250+"];
const TIER_F = [1, 0.9, 0.8, 0.7, 0.6];
function svc(
  role,
  title,
  type,
  desc,
  base,
  {
    tiers = TIERS,
    factors = TIER_F,
    kind = "transform",
    lead = 5,
    leadText = null,
    tags = [],
  } = {},
) {
  const leadTxt = leadText ?? `Standard lead time: ${lead} business days.`;
  return build(role, {
    title,
    type,
    desc: `${desc} ${leadTxt}`,
    tags: [
      `lead_time:${slug(leadText ?? lead + " business days")}`,
      "service",
      ...tags,
    ],
    options: { Quantity: tiers },
    price: (c) => base * factors[tiers.indexOf(val(c, "Quantity"))],
    stock: null,
    kind,
    exact: true,
  });
}
const fee = (role, title, type, desc, amount, kind = "transform", tags = []) =>
  build(role, {
    title,
    type,
    desc,
    tags: ["service", "fee", ...tags],
    price: amount,
    stock: null,
    kind,
    exact: true,
  });
const capacity = (role, title, perDay, kind) =>
  build(role, {
    title,
    type: "Capacity",
    desc: `Live daily capacity indicator: inventory equals units available per day. Setting this to 0 marks the merchant unavailable.`,
    tags: ["capacity", "live-signal"],
    price: 0,
    stock: [perDay, perDay],
    kind,
    exact: true,
  });


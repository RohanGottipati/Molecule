/**
 * Browse the stores mirrored into the read model: their catalog, orders, customers and sales.
 *
 * Reads the same routes in live and fake mode; only the provenance label differs.
 */
export function StoreConsole() {
  const [stores, setStores] = useState<StoreList | null>(null);
  const [selected, setSelected] = useState<string | null>(null);
  const [tab, setTab] = useState<Tab>("catalog");
  const [panel, setPanel] = useState<
    StoreCatalog | StoreOrders | StoreCustomers | StoreAnalytics | null
  >(null);
  const [error, setError] = useState<string | null>(null);
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    const controller = new AbortController();
    getStores(controller.signal)
      .then((list) => {
        setStores(list);
        setSelected((current) => current ?? list.stores[0]?.shopDomain ?? null);
      })
      .catch((cause: unknown) => {
        if (!controller.signal.aborted)
          setError(
            cause instanceof Error ? cause.message : "Could not load stores.",
          );
      })
      .finally(() => setLoading(false));
    return () => controller.abort();
  }, []);

  const load = useCallback(
    (domain: string, next: Tab, signal: AbortSignal) => {
      const readers = {
        catalog: getStoreCatalog,
        orders: getStoreOrders,
        customers: getStoreCustomers,
        analytics: getStoreAnalytics,
      } as const;
      return readers[next](domain, signal);
    },
    [],
  );

  useEffect(() => {
    if (!selected) return;
    const controller = new AbortController();
    setPanel(null);
    setError(null);
    load(selected, tab, controller.signal)
      .then((data) => setPanel(data))
      .catch((cause: unknown) => {
        if (!controller.signal.aborted)
          setError(
            cause instanceof Error
              ? cause.message
              : "Could not load this store.",
          );
      });
    return () => controller.abort();
  }, [selected, tab, load]);

  if (loading) return <p className="muted">Loading stores…</p>;

  if (!stores?.stores.length) {
    return (
      <Empty title="No stores mirrored yet">
        Run the Shopify sync to mirror store catalogs into the read model. With
        SHOPIFY_MODE=fake this needs no credentials.
      </Empty>
    );
  }

  const current: StoreSummary | undefined = stores.stores.find(
    (store) => store.shopDomain === selected,
  );

  return (
    <section className="store-console">
      <header>
        <h2>Stores</h2>
        <p className="muted small">
          {stores.stores.length} stores ·{" "}
          {stores.mode === "live"
            ? "Live Shopify"
            : stores.mode === "fake"
              ? "Local synthetic stores"
              : "Demo commerce"}
        </p>
      </header>

      <nav className="store-picker" aria-label="Stores">
        {stores.stores.map((store) => (
          <button
            key={store.shopDomain}
            type="button"
            className={store.shopDomain === selected ? "active" : undefined}
            aria-current={store.shopDomain === selected}
            onClick={() => setSelected(store.shopDomain)}
          >
            <strong>{store.merchantName}</strong>
            <span className="muted small">
              {store.productCount} products · {store.orderCount} orders
            </span>
          </button>
        ))}
      </nav>

      {current && (
        <p className="muted small">
          <code>{current.shopDomain}</code> · {current.variantCount} variants ·{" "}
          {current.trackedVariantCount} tracked · synced{" "}
          {dateLabel(current.syncedAt, true)}
        </p>
      )}

      <div className="store-tabs" role="tablist" aria-label="Store data">
        {tabs.map((entry) => (
          <button
            key={entry.key}
            type="button"
            role="tab"
            aria-selected={entry.key === tab}
            className={entry.key === tab ? "active" : undefined}
            onClick={() => setTab(entry.key)}
          >
            {entry.label}
          </button>
        ))}
      </div>

      <div role="tabpanel">
        {error && <p className="inline-warning">{error}</p>}
        {!error && !panel && <p className="muted">Loading…</p>}
        {panel && "products" in panel && <CatalogPanel data={panel} />}
        {panel && "orders" in panel && <OrdersPanel data={panel} />}
        {panel && "customers" in panel && <CustomersPanel data={panel} />}
        {panel && "totals" in panel && <AnalyticsPanel data={panel} />}
      </div>
    </section>
  );
}

// Synthetic merchant catalogs for the Molecule demo. Every product is tagged MOLECULE_DEMO.
// Deterministic: same input -> same handles, prices and stock, so seeding is idempotent.
const hashStr = (s) => {
  let x = 2166136261;
  for (const c of s) {
    x ^= c.charCodeAt(0);
    x = Math.imul(x, 16777619);
  }
  return x >>> 0;
};
const rng = (seed) => {
  let a = hashStr(seed);
  return () => {
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
};
export const slug = (s) =>
  s
    .toLowerCase()
    .replace(/&/g, "and")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
const money = (n) => (Math.round(n * 100) / 100).toFixed(2);
const cartesian = (opts) =>
  Object.entries(opts).reduce(
    (acc, [name, vals]) =>
      acc.flatMap((combo) =>
        vals.map((v) => [...combo, { optionName: name, name: v }]),
      ),
    [[]],
  );
const val = (combo, name) => combo.find((c) => c.optionName === name)?.name;

